# menentukan angka genap atau ganjil 
# menginput angka dari pengguna
angka=int(input("Masukkan angka berapapun yang anda inginkan yaa:"))

# memeriksa angka apakah angkanya genap atau ganjil
if angka % 2==0:
    print("angka ini adalah genap")
else:
    print("angka ini adalah ganjil")