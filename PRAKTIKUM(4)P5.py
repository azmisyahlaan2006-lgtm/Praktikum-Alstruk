# 1. Simpan poin awal dalam variabel poin
poin = 100
print(f"Langkah 1 (Nilai awal): {poin}")

# 2. Tambahkan 25 poin menggunakan +=
poin += 25
print(f"Langkah 2 (poin += 25): {poin}")

# 3. Kurangi 10 poin menggunakan -=
poin -= 10
print(f"Langkah 3 (poin -= 10): {poin}")

# 4. Kalikan poin dengan 2 menggunakan *=
poin *= 2
print(f"Langkah 4 (poin *= 2) : {poin}")

# 5. Bagi poin dengan 2 menggunakan /=
poin /= 2
print(f"Langkah 5 (poin /= 2) : {poin}")
